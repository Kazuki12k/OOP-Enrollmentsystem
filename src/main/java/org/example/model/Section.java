package org.example.model;

public class Section {
    String sectioncode;
    int maxCapacity = 30;

    public Section(){
        this.sectioncode = sectioncode;
        this.maxCapacity = maxCapacity;
    }

    public String getSectioncode() {
        return sectioncode;
    }

    public int getMaxCapacity() {
        return maxCapacity;
    }
}
